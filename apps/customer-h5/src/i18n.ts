const dictionaries = { en, hu }

function translate(source: string): string {
  if (language.value === 'zh') return source
  const dict = dictionaries[language.value]
  let result = source
  for (const key of Object.keys(dict).sort((a, b) => b.length - a.length))
    result = result.split(key).join(dict[key]!)
  return result
}
export const tr = translate

const originals = new WeakMap<Text, string>()
const attrOriginals = new WeakMap<Element, Map<string, string>>()
const renderedTexts = new WeakMap<Text, string>()
const renderedAttrs = new WeakMap<Element, Map<string, string>>()
let observer: MutationObserver | undefined

function apply(root: ParentNode = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  let node: Node | null
  while ((node = walker.nextNode())) {
    const text = node as Text
    const prior = originals.get(text)
    if (prior === undefined) originals.set(text, text.data)
    else if (renderedTexts.has(text) && text.data !== renderedTexts.get(text))
      originals.set(text, text.data)
    const translated = translate(originals.get(text) || '')
    if (text.data !== translated) text.data = translated
    renderedTexts.set(text, translated)
  }
  root.querySelectorAll?.('[placeholder],[title],[aria-label]').forEach((element) => {
    let map = attrOriginals.get(element)
    if (!map) {
      map = new Map()
      attrOriginals.set(element, map)
    }
    let rendered = renderedAttrs.get(element)
    if (!rendered) {
      rendered = new Map()
      renderedAttrs.set(element, rendered)
    }
    for (const name of ['placeholder', 'title', 'aria-label']) {
      const current = element.getAttribute(name)
      if (current === null) continue
      const prior = map.get(name)
      if (prior === undefined || (rendered.has(name) && current !== rendered.get(name)))
        map.set(name, current)
      const translated = translate(map.get(name) || '')
      if (current !== translated) element.setAttribute(name, translated)
      rendered.set(name, translated)
    }
  })
}
export function setLanguage(value: Language) {
  language.value = value
  localStorage.setItem('budapest-language', value)
  document.documentElement.lang = value === 'zh' ? 'zh-CN' : value
  void nextTick(() => apply())
}
export function useDomI18n() {
  onMounted(() => {
    apply()
    observer = new MutationObserver(() => apply())
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['placeholder', 'title', 'aria-label'],
    })
  })
  onUnmounted(() => observer?.disconnect())
}
